#!/usr/bin/env python3
"""Regenerate docs/assets/search-index.js from the h2/h3 headings of every page.

Run after adding or renaming sections: python3 website/update-search-index.py
The site works without it; search then covers page titles and the current page only.
"""
import html, json, re, pathlib

DOCS = pathlib.Path(__file__).resolve().parent / "docs"
HEAD = re.compile(r'<h([23])[^>]*\bid="([^"]+)"[^>]*>(.*?)</h\1>', re.S)

index = {}
for page in sorted(DOCS.rglob("*.html")):
    rel = page.relative_to(DOCS).as_posix()
    if rel.startswith("_"):
        continue
    heads = []
    for _, hid, inner in HEAD.findall(page.read_text(encoding="utf-8")):
        text = html.unescape(re.sub(r"<[^>]+>", "", inner)).strip()
        if text:
            heads.append([hid, text])
    index[rel] = heads

out = DOCS / "assets" / "search-index.js"
out.write_text("// Generated by website/update-search-index.py. Do not edit.\nwindow.TRELLIS_SEARCH = "
               + json.dumps(index, ensure_ascii=False, indent=0, sort_keys=True) + ";\n", encoding="utf-8")
print(f"{out.relative_to(DOCS.parent)}: {sum(len(v) for v in index.values())} headings in {len(index)} pages")
